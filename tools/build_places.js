const byC = {};
for (const x of data) {
  if (!x.timezone || !x.iso2 || x.iso2 === "KR") continue;
  (byC[x.iso2] = byC[x.iso2] || []).push(x);
}
for (const [cc, list] of Object.entries(byC)) {
  list.sort((a, b) => (b.pop || 0) - (a.pop || 0));
  const seen = new Map();
  for (const x of list) seen.set(x.city, (seen.get(x.city) || 0) + 1);
  const used = new Set();
  out2[cc] = list.map((x) => {
    let name = x.city;
    if (seen.get(x.city) > 1 && x.province) name = `${x.city}, ${x.province}`;
    if (used.has(name)) return null;
    used.add(name);
    return [name, +x.lat.toFixed(3), +x.lng.toFixed(3), tzi(x.timezone)];
  }).filter(Boolean);
}
